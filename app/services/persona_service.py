"""Bundled AI personas (skills/personalities) from The Agency.

The data file `app/data/agency_personas.json` is generated by
`tools/convert_agency_personas.py` from the agency-agents repo (MIT —
attribution in NOTICE.md and licenses/AGENCY-AGENTS-LICENSE.txt).

Personas are reusable system-prompt personalities: the Automation module
offers them in the AI nodes' behavior field, and the AI chat can inject one
into a conversation. User-made behaviors (core, see behavior_service) stay
alongside them — a persona is just a curated, read-only behavior.

Users can enable/disable individual personas (PersonaPref rows); pickers
list only the enabled ones so the choice stays manageable.
"""

import json
import os

from ..extensions import db
from ..models import PersonaPref

_DATA_PATH = os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "data", "agency_personas.json")

_cache = None


def _load():
    """{key: persona} map, parsed once per process."""
    global _cache
    if _cache is None:
        with open(_DATA_PATH, encoding="utf-8") as fh:
            data = json.load(fh)
        _cache = {p["key"]: p for p in data["personas"]}
    return _cache


def list_personas(user_id=None, enabled_only=False):
    """Light persona summaries (no content), grouped by division.

    With ``user_id`` each summary gains an ``enabled`` flag (default True);
    with ``enabled_only`` the disabled ones are filtered out."""
    prefs = {}
    if user_id is not None:
        prefs = {p.persona_key: p.enabled
                 for p in PersonaPref.query.filter_by(user_id=user_id)}
    items = []
    for p in _load().values():
        enabled = prefs.get(p["key"], True)
        if enabled_only and not enabled:
            continue
        item = {"key": p["key"], "name": p["name"], "division": p["division"],
                "description": p["description"], "emoji": p["emoji"],
                "color": p["color"], "vibe": p["vibe"]}
        if user_id is not None:
            item["enabled"] = bool(enabled)
        items.append(item)
    return sorted(items, key=lambda p: (p["division"], p["name"]))


def divisions():
    """Ordered division names present in the library."""
    seen = []
    for p in list_personas():
        if p["division"] not in seen:
            seen.append(p["division"])
    return seen


def get_persona(key):
    """Full persona dict (with content), or None."""
    return _load().get(key)


def system_prompt(key):
    """The persona's system-prompt body, or None for unknown keys."""
    persona = get_persona(key)
    return persona["content"] if persona else None


def is_persona_enabled(user_id, key):
    """Personas are enabled by default; a PersonaPref row overrides."""
    pref = (PersonaPref.query
            .filter_by(user_id=user_id, persona_key=key).first())
    return pref.enabled if pref else True


def set_persona_enabled(user_id, key, enabled):
    """Toggle one persona for a user. Unknown keys are rejected."""
    if key not in _load():
        return None
    pref = (PersonaPref.query
            .filter_by(user_id=user_id, persona_key=key).first())
    if pref is None:
        pref = PersonaPref(user_id=user_id, persona_key=key)
        db.session.add(pref)
    pref.enabled = bool(enabled)
    db.session.commit()
    return pref.enabled


def set_division_enabled(user_id, division, enabled):
    """Enable/disable every persona in a division in one go.

    Returns the number of personas affected, or None for unknown divisions."""
    keys = [p["key"] for p in _load().values() if p["division"] == division]
    if not keys:
        return None
    prefs = {p.persona_key: p
             for p in PersonaPref.query.filter_by(user_id=user_id)}
    for key in keys:
        pref = prefs.get(key)
        if pref is None:
            pref = PersonaPref(user_id=user_id, persona_key=key)
            db.session.add(pref)
        pref.enabled = bool(enabled)
    db.session.commit()
    return len(keys)
